-- ── Firms (multi-tenancy) ────────────────────────────────────────────────────
-- Every connection and user belongs to a firm. Firm 1 ("Default") is created
-- here so a single-firm installation keeps working exactly as before.
CREATE TABLE IF NOT EXISTS firms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active', 'suspended')),
  plan TEXT,
  company_limit INTEGER,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

INSERT INTO firms (id, name, slug) VALUES (1, 'Default', 'default') ON CONFLICT DO NOTHING;
SELECT setval(pg_get_serial_sequence('firms', 'id'), GREATEST((SELECT MAX(id) FROM firms), 1));

ALTER TABLE connections ADD COLUMN IF NOT EXISTS firm_id INTEGER NOT NULL DEFAULT 1 REFERENCES firms(id);
ALTER TABLE users ADD COLUMN IF NOT EXISTS firm_id INTEGER NOT NULL DEFAULT 1 REFERENCES firms(id);

CREATE INDEX IF NOT EXISTS idx_connections_firm ON connections(firm_id);
CREATE INDEX IF NOT EXISTS idx_users_firm ON users(firm_id);
